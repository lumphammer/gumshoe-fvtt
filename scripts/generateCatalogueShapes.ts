// Writes the catalogue's shapes, from its recipes (the ones registered in
// panda.config.ts) and their element states (elementStateDefaults.ts): each
// recipe's class name, slots, variants with their values, and states.
// (A recipe can also have its own default for a state layer, as the logo has
// for hover feedback: that goes in the CSS, and not in its shape, as any
// recipe's elements can have the state layers.)
// ThemeV2's overrides are typed and checked against them (docs/theming.md,
// "Themes (ThemeV2)"). And from the states, their defaults as CSS, in each
// state's layer, and the table of them in docs/theming.md. And the types
// package's JSON schemas, whose catalogue is built from the shapes
// (jsonSchemas.ts).
//
//   pnpm generate:catalogue          writes the files
//   pnpm generate:catalogue --check  fails if they're out of date
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import type {
  ElementState,
  StateLayer,
  ThemeStyle,
} from "@lumphammer/investigator-fvtt-types";

import config from "../panda.config";
import {
  elementStateDefaults,
  type StateDefault,
} from "../src/themes/catalogue/elementStateDefaults";
import {
  elementStates,
  elementStateTells,
  isElementState,
  isStateLayer,
  stateLayers,
} from "../src/themes/catalogue/stateLayers";
import { styleCss } from "../src/themes/catalogue/styleCss";
import { buildJsonSchemas, schemasDir } from "./jsonSchemas";

const root = join(import.meta.dirname, "..");
const header = `// Generated by scripts/generateCatalogueShapes.ts from the catalogue's
// recipes (src/themes/catalogue): don't edit. Run \`pnpm generate:catalogue\`.
`;

interface Shape {
  className: string;
  slots: string[];
  variants: Record<string, string[]>;
  states: string[];
}

/** Stop, with what's wrong. */
const fail = (message: string): never => {
  console.error(message);
  process.exit(1);
};

/** Each nested selector in a style (or in a style for each slot). */
const nestedKeys = (style: object): string[] =>
  Object.entries(style).flatMap(([key, value]) =>
    value && typeof value === "object" && !Array.isArray(value)
      ? [key, ...nestedKeys(value)]
      : [],
  );

const recipes: Record<string, { className?: string; variants?: object }> = {
  ...config.theme?.recipes,
  ...config.theme?.slotRecipes,
};

const elementStateOrder = Object.keys(elementStates) as ElementState[];

for (const [name, states] of Object.entries(elementStateDefaults)) {
  if (!Object.hasOwn(recipes, name)) {
    fail(`elementStateDefaults: no such recipe "${name}"`);
  }
  for (const state of Object.keys(states)) {
    if (!isElementState(state) && !isStateLayer(state)) {
      fail(`elementStateDefaults.${name}: no such state "${state}"`);
    }
  }
}

const shapes: [string, Shape][] = Object.entries(recipes)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, recipe]) => {
    const slots = "slots" in recipe ? (recipe.slots as string[]) : [];
    // a variant's `states` sit beside its slots' styles
    if (slots.includes("states")) {
      fail(`${name}: a slot can't be called "states"`);
    }
    const states = elementStateOrder.filter((state) =>
      Object.hasOwn(elementStateDefaults[name] ?? {}, state),
    );
    // a recipe's own look for one of its states would lose to the state's
    // default (and to a theme's override of it): it belongs in its states
    for (const key of nestedKeys(recipe)) {
      const state = states.find((state) => elementStateTells[state].test(key));
      if (state) {
        fail(
          `${name}: "${key}" is the ${state} state: style it in its states (elementStateDefaults.ts)`,
        );
      }
    }
    return [
      name,
      {
        className: recipe.className!,
        slots,
        variants: Object.fromEntries(
          Object.entries(recipe.variants ?? {}).map(([variant, values]) => [
            variant,
            Object.keys(values as object),
          ]),
        ),
        states,
      },
    ];
  });

const union = (values: string[]) =>
  values.length > 0
    ? values.map((v) => JSON.stringify(v)).join(" | ")
    : "never";

const types = `${header}
/**
 * The catalogue's recipes, by name: each one's slots (\`never\` for a recipe
 * without), variants, with their values (\`"true" | "false"\` for a boolean
 * one), and element states (\`never\` for a recipe without).
 */
export interface CatalogueRecipeShapes {
${shapes
  .map(
    ([name, { slots, variants, states }]) => `  ${name}: {
    slots: ${union(slots)};
    states: ${union(states)};
    variants: ${
      Object.keys(variants).length > 0
        ? `{${Object.entries(variants)
            .map(([variant, values]) => ` ${variant}: ${union(values)};`)
            .join("")} }`
        : "Record<never, never>"
    };
  };`,
  )
  .join("\n")}
}
`;

const runtime = `${header}
/**
 * The catalogue's recipes, by name: each one's class name, slots, variants,
 * with their values, and element states.
 */
export const recipeShapes = ${JSON.stringify(Object.fromEntries(shapes))} as const;
`;

/** A state's default for each part: its slot (none, for a plain recipe). */
const defaultParts = (
  name: string,
  state: ElementState | StateLayer,
  shape: Shape,
  style: StateDefault,
): [string | undefined, ThemeStyle][] => {
  if (shape.slots.length === 0) return [[undefined, style as ThemeStyle]];
  return Object.entries(style).map(([slot, part]) => {
    if (!shape.slots.includes(slot)) {
      fail(`elementStateDefaults.${name}.${state}: no such slot "${slot}"`);
    }
    return [slot, part as ThemeStyle];
  });
};

/**
 * One state's defaults, for every recipe that has it, in its layer. A state
 * layer's are in its `default` sub-layer, with its default for everything
 * (states.css), and scoped as that is, so they're more specific than it.
 */
const stateBlock = (state: ElementState | StateLayer) => {
  const { defaultLayer, selectors } = isStateLayer(state)
    ? stateLayers[state]
    : elementStates[state];
  const scope = isStateLayer(state) ? "[data-inv-theme] " : "";
  const rules = shapes.flatMap(([name, shape]) => {
    const style = elementStateDefaults[name]?.[state];
    if (!style) return [];
    return defaultParts(name, state, shape, style).map(([slot, part]) => {
      const element = `.${shape.className}${slot ? `__${slot}` : ""}`;
      return `${selectors(element)
        .map((selector) => `${scope}${selector}`)
        .join(", ")} { ${styleCss(part)} }`;
    });
  });
  return rules.length > 0
    ? `@layer ${defaultLayer} { ${rules.join(" ")} }`
    : "";
};

/** Each recipe's element states' defaults, as CSS, in each state's layer. */
const statesCss = `/*
 * Generated by scripts/generateCatalogueShapes.ts from the recipes' element
 * states (src/themes/catalogue/elementStateDefaults.ts): don't edit. Run
 * \`pnpm generate:catalogue\`.
 *
 * Each state's defaults, in its layer (states.css has the order), where a
 * theme's changes to them go too. Then a recipe's own defaults for a state
 * layer, in its \`default\` sub-layer (a theme's changes go after them).
 */
${[...elementStateOrder, ...(Object.keys(stateLayers) as StateLayer[])]
  .map(stateBlock)
  .filter(Boolean)
  .join("\n")}
`;

const code = (text: string) => `\`${text}\``;

/** The table of which recipe has which element states, for the docs. */
const statesTable = [
  `| Recipe | ${elementStateOrder.map(code).join(" | ")} |`,
  `| --- | ${elementStateOrder.map(() => "---").join(" | ")} |`,
  ...shapes
    .filter(([, { states }]) => states.length > 0)
    .map(
      ([name, { states }]) =>
        `| ${code(name)} | ${elementStateOrder
          .map((state) => (states.includes(state) ? "✓" : ""))
          .join(" | ")} |`,
    ),
].join("\n");

const docsPath = "docs/theming.md";
const tableStart = "<!-- element-states:start (pnpm generate:catalogue) -->";
const tableEnd = "<!-- element-states:end -->";
const docs = readFileSync(join(root, docsPath), "utf8");
const [before, rest] = docs.split(tableStart);
const after = rest?.split(tableEnd)[1];
if (after === undefined) fail(`${docsPath}: no ${tableStart} ... ${tableEnd}`);
const docsWithTable = `${before}${tableStart}\n\n${statesTable}\n\n${tableEnd}${after}`;

const format = (path: string, source: string) => {
  const result = spawnSync(
    "pnpm",
    ["exec", "oxfmt", `--stdin-filepath=${path}`],
    {
      cwd: root,
      input: source,
      encoding: "utf8",
    },
  );
  if (result.status !== 0) throw new Error(result.stderr);
  return result.stdout;
};

const files: [string, string][] = [
  ["packages/investigator-fvtt-types/catalogue.generated.ts", types],
  ["src/themes/catalogue/recipeShapes.generated.ts", runtime],
  ["src/themes/catalogue/elementStates.generated.css", statesCss],
  [docsPath, docsWithTable],
  ...buildJsonSchemas(shapes).map(([file, json]): [string, string] => [
    `${schemasDir}/${file}`,
    json,
  ]),
];

const check = process.argv.includes("--check");
let stale = false;
for (const [path, source] of files) {
  const full = join(root, path);
  const wanted = format(path, source);
  let current = "";
  try {
    current = readFileSync(full, "utf8");
  } catch {
    // not there yet
  }
  if (current === wanted) continue;
  if (check) {
    console.error(`${path} is out of date: run \`pnpm generate:catalogue\``);
    stale = true;
  } else {
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, wanted);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
