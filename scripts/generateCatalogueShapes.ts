// Writes the catalogue's shapes, from its recipes (the ones registered in
// panda.config.ts): each recipe's class name, slots and variants, with their
// values. ThemeV2's overrides are typed and checked against them
// (docs/theming.md, "Themes (ThemeV2)").
//
//   pnpm generate:catalogue          writes the files
//   pnpm generate:catalogue --check  fails if they're out of date
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import config from "../panda.config";

const root = join(import.meta.dirname, "..");
const header = `// Generated by scripts/generateCatalogueShapes.ts from the catalogue's
// recipes (src/themes/catalogue): don't edit. Run \`pnpm generate:catalogue\`.
`;

interface Shape {
  className: string;
  slots: string[];
  variants: Record<string, string[]>;
}

const recipes: Record<string, { className?: string; variants?: object }> = {
  ...config.theme?.recipes,
  ...config.theme?.slotRecipes,
};

const shapes: [string, Shape][] = Object.entries(recipes)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, recipe]) => [
    name,
    {
      className: recipe.className!,
      slots: "slots" in recipe ? (recipe.slots as string[]) : [],
      variants: Object.fromEntries(
        Object.entries(recipe.variants ?? {}).map(([variant, values]) => [
          variant,
          Object.keys(values as object),
        ]),
      ),
    },
  ]);

const union = (values: string[]) =>
  values.length > 0
    ? values.map((v) => JSON.stringify(v)).join(" | ")
    : "never";

const types = `${header}
/**
 * The catalogue's recipes, by name: each one's slots (\`never\` for a recipe
 * without) and variants, with their values (\`"true" | "false"\` for a
 * boolean one).
 */
export interface CatalogueRecipeShapes {
${shapes
  .map(
    ([name, { slots, variants }]) => `  ${name}: {
    slots: ${union(slots)};
    variants: ${
      Object.keys(variants).length > 0
        ? `{${Object.entries(variants)
            .map(([variant, values]) => ` ${variant}: ${union(values)};`)
            .join("")} }`
        : "Record<never, never>"
    };
  };`,
  )
  .join("\n")}
}
`;

const runtime = `${header}
/**
 * The catalogue's recipes, by name: each one's class name, slots and
 * variants, with their values.
 */
export const recipeShapes = ${JSON.stringify(Object.fromEntries(shapes))} as const;
`;

const format = (path: string, source: string) => {
  const result = spawnSync(
    "pnpm",
    ["exec", "oxfmt", `--stdin-filepath=${path}`],
    {
      cwd: root,
      input: source,
      encoding: "utf8",
    },
  );
  if (result.status !== 0) throw new Error(result.stderr);
  return result.stdout;
};

const files: [string, string][] = [
  ["packages/investigator-fvtt-types/catalogue.generated.ts", types],
  ["src/themes/catalogue/recipeShapes.generated.ts", runtime],
];

const check = process.argv.includes("--check");
let stale = false;
for (const [path, source] of files) {
  const full = join(root, path);
  const wanted = format(path, source);
  let current = "";
  try {
    current = readFileSync(full, "utf8");
  } catch {
    // not there yet
  }
  if (current === wanted) continue;
  if (check) {
    console.error(`${path} is out of date: run \`pnpm generate:catalogue\``);
    stale = true;
  } else {
    writeFileSync(full, wanted);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
