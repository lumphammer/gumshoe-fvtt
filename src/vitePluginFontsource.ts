/**
 * Our translations are all in Latin script (Japanese aside, which none of
 * these fonts cover), so we skip Cyrillic, Greek, Vietnamese etc.
 */
const subsets = ["latin", "latin-ext"];

/** Where the fonts go, relative to the build directory. */
const cssFileName = "fonts/fontsource.css";
const filesDir = "fonts/fontsource";

type FontFile = { fileName: string; sourcePath: string };

/**
 * Turn one of Fontsource's stylesheets into `@font-face` rules for the subsets
 * we want, pointing at `woff2` files only (every browser Foundry supports can
 * read them, so the `woff` fallbacks would only make the package bigger).
 */
export function convertFontsourceCss(css: string, family: string) {
  const faces: string[] = [];
  const files: string[] = [];
  const ruleRegex = /\/\* (\S+) \*\/\s*@font-face \{([^}]*)\}/g;
  for (const [, name, body] of css.matchAll(ruleRegex)) {
    const subset = /-(latin(?:-ext)?)-[^-]+-(?:normal|italic)$/.exec(name)?.[1];
    if (subset === undefined || !subsets.includes(subset)) continue;
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)?.[1];
    if (file === undefined) {
      throw new Error(`No woff2 file in Fontsource rule ${name}`);
    }
    files.push(file);
    const declarations = body
      .trim()
      .split(/;\s*/)
      .filter((declaration) => declaration !== "")
      .map((declaration) => {
        if (declaration.startsWith("font-family:")) {
          return `font-family: '${family}'`;
        }
        if (declaration.startsWith("src:")) {
          return `src: url(./fontsource/${file}) format('woff2')`;
        }
        return declaration;
      });
    faces.push(
      `/* ${name} */\n@font-face {\n${declarations.map((d) => `  ${d};`).join("\n")}\n}\n`,
    );
  }
  return { faces, files };
}

export function buildFonts(families: FontsourceFamily[], rootDir: string) {
  const require = createRequire(resolve(rootDir, "package.json"));
  const files: FontFile[] = [];
  const cssParts = [
    "/* Generated by vitePluginFontsource from Fontsource packages. */\n",
  ];
  for (const { family, pkg, css } of families) {
    const pkgDir = dirname(require.resolve(`${pkg}/package.json`));
    files.push({
      fileName: `${filesDir}/${basename(pkg)}-LICENSE`,
      sourcePath: resolve(pkgDir, "LICENSE"),
    });
    for (const cssName of css) {
      const converted = convertFontsourceCss(
        readFileSync(resolve(pkgDir, `${cssName}.css`), "utf8"),
        family,
      );
      if (converted.faces.length === 0) {
        throw new Error(`No Latin @font-face rules in ${pkg}/${cssName}.css`);
      }
      cssParts.push(...converted.faces);
      files.push(
        ...converted.files.map((file) => ({
          fileName: `${filesDir}/${file}`,
          sourcePath: resolve(pkgDir, "files", file),
        })),
      );
    }
  }
  return { css: cssParts.join("\n"), files };
}

/**
 * Self-host our theme fonts from Fontsource packages, rather than loading them
 * from Google Fonts (which sends each user's IP address to Google).
 *
 * Writes `fonts/fontsource.css` (listed in `system.json`) and the `woff2` files
 * it points at. We can't just `import` Fontsource's CSS, because library mode
 * inlines every asset into the bundle as base64, so every user would download
 * every font. Browsers only fetch a font file when a page uses it.
 */
export function vitePluginFontsource({
  families = fontsourceFamilies,
}: { families?: FontsourceFamily[] } = {}): PluginOption {
  let rootDir = process.cwd();
  let base = "/";
  return {
    name: "fontsource",

    configResolved(config) {
      // vite's root is `src/`; node_modules lives in the parent
      rootDir = resolve(config.root, "..");
      base = config.base;
    },

    configureServer(server) {
      const { css, files } = buildFonts(families, rootDir);
      const sourcePaths = new Map(
        files.map(({ fileName, sourcePath }) => [fileName, sourcePath]),
      );
      server.middlewares.use((req, res, next) => {
        const path = req.url?.split("?")[0] ?? "";
        if (!path.startsWith(base)) return next();
        const fileName = path.slice(base.length);
        if (fileName === cssFileName) {
          res.setHeader("Content-Type", "text/css");
          res.end(css);
          return;
        }
        const sourcePath = sourcePaths.get(fileName);
        if (sourcePath === undefined) return next();
        res.setHeader(
          "Content-Type",
          fileName.endsWith(".woff2") ? "font/woff2" : "text/plain",
        );
        res.end(readFileSync(sourcePath));
      });
    },

    generateBundle() {
      const { css, files } = buildFonts(families, rootDir);
      this.emitFile({ type: "asset", fileName: cssFileName, source: css });
      for (const { fileName, sourcePath } of files) {
        this.emitFile({
          type: "asset",
          fileName,
          source: readFileSync(sourcePath),
        });
      }
    },
  };
}
